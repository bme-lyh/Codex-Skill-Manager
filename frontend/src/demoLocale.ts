export function demoLocaleFromLocation(): AppLocale {
  const requested = new URLSearchParams(window.location.search).get("lang");
  return requested === "en-US" ? "en-US" : "zh-CN";
}

export function localizeDemo<T>(value: T, locale: AppLocale): T {
  if (locale !== "en-US") return value;
  if (typeof value === "string") return (englishDemoText[value] ?? value) as T;
  if (Array.isArray(value)) return value.map(item => localizeDemo(item, locale)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localizeDemo(item, locale)])
    ) as T;
  }
  return value;
}
